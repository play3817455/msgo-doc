def apply_patches() -> list[str]:
    completed: list[str] = []
    for table_id, col_patches in PATCHES.items():
        path = TABLES / f"{table_id}.json"
        data = json.loads(path.read_text(encoding="utf-8"))
        by_idx = {c["csv_index"]: c for c in data["columns"]}
        for idx, patch in col_patches.items():
            if idx not in by_idx:
                raise KeyError(f"{table_id} missing csv_index {idx}")
            by_idx[idx].update(patch)
        data = finalize_table(data)
        path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
        if data["asm_status"] == "complete":
            completed.append(table_id)
        print(f"{table_id}: asm={data['asm_status']} pending={data['column_pending']}")
    return completed


